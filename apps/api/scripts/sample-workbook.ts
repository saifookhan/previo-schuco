import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import * as XLSX from 'xlsx'

/**
 * A small, entirely made-up product family in the Excel import format
 * (`src/lib/excel-import`) — safe to publish in the docs, unlike the real
 * supplier workbook in `tests/fixtures`. Used by `seed-demo-family.ts` and
 * written to the docs site as the downloadable sample.
 */
export const SAMPLE_FAMILY_NAME = 'Demo Window W70'

const MATRIX_SHEET = 'Matrice_1anta'

export const buildSampleWorkbook = (): Buffer => {
  const workbook = XLSX.utils.book_new()

  XLSX.utils.book_append_sheet(
    workbook,
    XLSX.utils.json_to_sheet([
      { Label: 'Nome_famiglia', Value: SAMPLE_FAMILY_NAME },
      { Label: 'Nome_tecnico_famiglia', Value: 'W70-DEMO' },
      { Label: 'Categoria prodotti', Value: 'Finestre' },
      { Label: 'Brand/Fornitore', Value: 'PREVIO Demo' },
      { Label: 'Descrizione_1', Value: 'Sample aluminium window series for testing — prices are fictional' },
      { Label: 'Descrizione_2', Value: 'Generated by apps/api/scripts/sample-workbook.ts' },
    ]),
    'Product Family',
  )

  XLSX.utils.book_append_sheet(
    workbook,
    XLSX.utils.json_to_sheet([
      {
        Index: 1,
        Nome_linea_prodotto: 'Finestra 1 anta',
        Descrizione_opzionale: 'Single-sash window, priced from a width × height table',
        Tipo_Listino: 'Tabella BxH [€/Pz]',
        Listino_acquisto: MATRIX_SHEET,
        Nome_UM: 'Pezzo',
        Simbolo_UM: 'pz',
        'Sconto %': 0.1,
        'MarkUp %': 1.3,
        'Ore di posa x UM': 1.5,
      },
      {
        Index: 2,
        Nome_linea_prodotto: 'Finestra 2 ante',
        Descrizione_opzionale: 'Double-sash window, priced per m²',
        Tipo_Listino: 'Superficie x [€/m2]',
        Listino_acquisto: 280,
        Nome_UM: 'Metro quadro',
        Simbolo_UM: 'm²',
        'Sconto %': 0.1,
        'MarkUp %': 1.3,
        'Ore di posa x UM': 2,
      },
      {
        Index: 3,
        Nome_linea_prodotto: 'Zanzariera',
        Descrizione_opzionale: 'Insect screen, priced per metre of perimeter',
        Tipo_Listino: 'Perimetro x [€/m]',
        Listino_acquisto: 18,
        Nome_UM: 'Metro',
        Simbolo_UM: 'm',
        'Sconto %': 0,
        'MarkUp %': 1.4,
        'Ore di posa x UM': 0.5,
      },
    ]),
    'Product lines',
  )

  // Row 1: main characteristic names, three columns apart. The row holding
  // "Nome valore" is the header; every row after it is [name, type, price].
  XLSX.utils.book_append_sheet(
    workbook,
    XLSX.utils.aoa_to_sheet([
      ['Caratteristiche'],
      ['Vetro', null, null, 'Colore', null, null, 'Maniglia'],
      ['Nome valore', 'Tipo listino', 'Valore', 'Nome valore', 'Tipo listino', 'Valore', 'Nome valore', 'Tipo listino', 'Valore'],
      ['Doppio vetro', 'Superficie x [€/m2]', 0, 'Bianco', 'Valore_Fisso [€/Pz]', 0, 'Standard', 'Valore_Fisso [€/Pz]', 0],
      ['Triplo vetro', 'Superficie x [€/m2]', 45, 'Antracite', '% sul valore base del prodotto', 0.08, 'Con chiave', 'Valore_Fisso [€/Pz]', 35],
      ['Vetro acustico', 'Superficie x [€/m2]', 60, 'Effetto legno', '% sul valore base del prodotto', 0.15, 'Design inox', 'Valore_Fisso [€/Pz]', 55],
    ]),
    'Caracteristics',
  )

  XLSX.utils.book_append_sheet(
    workbook,
    XLSX.utils.json_to_sheet([
      { 'Product line / Caracteristics': 'Finestra 1 anta', Vetro: 'x', Colore: 'x', Maniglia: 'x' },
      { 'Product line / Caracteristics': 'Finestra 2 ante', Vetro: 'x', Colore: 'x', Maniglia: 'x' },
      { 'Product line / Caracteristics': 'Zanzariera', Vetro: '', Colore: 'x', Maniglia: '' },
    ]),
    'Relations',
  )

  // Width (mm) across, height (mm) down, price per piece in the cells.
  XLSX.utils.book_append_sheet(
    workbook,
    XLSX.utils.aoa_to_sheet([
      ['H \\ B', 600, 800, 1000, 1200],
      [800, 210, 240, 270, 300],
      [1200, 260, 295, 330, 365],
      [1600, 310, 350, 390, 430],
    ]),
    MATRIX_SHEET,
  )

  return XLSX.write(workbook, { type: 'buffer', bookType: 'xlsx' }) as Buffer
}

// `tsx scripts/sample-workbook.ts` regenerates the docs' downloadable copy.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = join(dirname(fileURLToPath(import.meta.url)), '../../docs/static/samples/previo-sample-family.xlsx')
  writeFileSync(target, buildSampleWorkbook())
  console.log(`Wrote ${target}`)
}
